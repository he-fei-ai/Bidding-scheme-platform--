class TestCorpusDrivesConflictDetection:
    """抽取结果直接决定冲突判定；这里钉住三条端到端联动。"""

    def test_same_amount_different_units_is_not_a_conflict(self):
        """「1200 万元」与「12000000 元」同值不同单位 → 不得判冲突（2026-10-09）。"""
        facts = AUDITOR.extract_facts_from_text("合同价 1200 万元；造价 12000000 元。")
        values = [f.value for f in facts]
        distinct = ConsistencyAuditor._distinct_values(values, fact_name="金额")
        assert len(distinct) == 1, f"同值不同单位应归一为一种表述，实际 {distinct}"

    def test_role_headcounts_are_separate_facts(self):
        """不同岗位人数不互判冲突（2026-10-04）：事实名按岗位分桶。"""
        facts = AUDITOR.extract_facts_from_text("项目经理 1 人、技术负责人 2 人。")
        names = {f.name for f in facts}
        assert names == {"项目经理数量", "技术负责人数量"}
        # 每个桶只有一个值 → 单桶内部无冲突
        for name in names:
            bucket = [f.value for f in facts if f.name == name]
            assert len(set(bucket)) == 1

    def test_calendar_day_forms_unify_to_one_value(self):
        """「450 日历天」「450 个日历天」「450 自然日」归一到同一取值（2026-10-10）。"""
        values = []
        for text in ("建设工期：450 日历天", "总工期 450 个日历天", "合同工期为 450 自然日"):
            values.extend(f.value for f in AUDITOR.extract_facts_from_text(text))
        assert set(values) == {"450"}
