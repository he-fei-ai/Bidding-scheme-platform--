"""一致性校核 —— 事实抽取规则回归语料库（G5 补齐，2026-10-13 第六轮）。

## 为什么需要这个文件

`ConsistencyAuditor.FACT_PATTERNS` 是**手写正则**：六类事实项（工期/金额/
人员数量/资质等级/质量标准/安全标准）的抽取口径散落在正则里，历史上每一轮
加固都在改它们（2026-10-04 分岗位、2026-10-09 金额单位、2026-10-10 资质
等级与人数结构校验、2026-10-11 总括人数与动词表收窄……）。此前的测试各自
只覆盖「本轮修的那一条」，没有任何地方把**全部事实项的当前期望行为**固化
成一份可回归的基线 —— 改一条正则只跑既有单测，很容易在另一类事实项上悄悄
引入漏抽/误抽而无人发现（规则漂移只能靠人发现，正是审计报告 G5 的原话）。

本文件把采集于 2026-10-13 的**当前真实行为**（探针实测，非人工编造）钉成
参数化语料库：

- 每条用例 = (输入文本, 期望 [(fact_name, value), ...])；
- 覆盖 6 类事实项 × 正例/负例/边界，含跨轮修复过的全部形态；
- 未来任何正则改动若改变了抽取结果，这里会**先于线上**报出差异，
  改动者必须显式更新语料（review 正则的成本从「全文推理」降为「看 diff」。

注意：语料钉的是**行为**不是**正则文本** —— 允许等价重构（如把两条分支合并），
只要同一输入的抽取结果不变。
"""

