@pytest.mark.parametrize(
    ("text", "expected"),
    CORPUS,
    ids=[text[:24] if text else "<empty>" for text, _ in CORPUS],
)
def test_fact_extraction_corpus(text: str, expected: list[tuple[str, str]]):
    """语料库主断言：同一输入的抽取结果必须与基线逐条一致。"""
    facts = AUDITOR.extract_facts_from_text(text)
    actual = [(f.name, f.value) for f in facts]
    assert actual == expected, (
        f"抽取结果与语料库基线不一致：\n  输入: {text!r}\n"
        f"  期望: {expected}\n  实际: {actual}\n"
        "若是有意修改规则，请同步更新本语料库（review 正则 = 看这条 diff）"
    )


