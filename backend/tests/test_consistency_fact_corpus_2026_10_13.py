class TestCorpusSelfConsistency:
    def test_corpus_covers_all_base_fact_names(self):
        """六类基础事实项都必须在语料里有正例（防止新增事实项忘了补语料）。"""
        from app.services import consistency_rules as rules

        covered = {name for _, expected in CORPUS for name, _ in expected}
        for fact_name in rules.BASE_FACT_NAMES:
            assert fact_name in covered, f"语料库缺少事实项 {fact_name!r} 的正例"

    def test_corpus_includes_negative_cases(self):
        """每类事实项至少一条负例（负例是防误抽的第一道闸）。"""
        negative = [text for text, expected in CORPUS if not expected]
        assert len(negative) >= 10, f"负例太少（{len(negative)}），误抽回归强度不足"

    def test_extraction_is_deterministic(self):
        """同一输入重复抽取结果一致（正则无随机性，钉住防回归）。"""
        for text, expected in CORPUS:
            first = [(f.name, f.value) for f in AUDITOR.extract_facts_from_text(text)]
            second = [(f.name, f.value) for f in AUDITOR.extract_facts_from_text(text)]
            assert first == second == expected


