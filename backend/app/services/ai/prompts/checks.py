# 与 `consistency_auditor` 的确定性路径分工：
#   - 确定性路径只能把「同一个值写成两种写法」统一成一种（如工期 30 / 45）；
#   - 本提示词处理的是**不同措辞表达同一事实**的冲突（如正文写「2026 年 5 月竣工」
