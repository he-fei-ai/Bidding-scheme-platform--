_LEVEL_CN_NAMES: dict[int, str] = {1: "一级", 2: "二级", 3: "三级", 4: "四级", 5: "五级", 6: "六级", 7: "七级", 8: "八级"}

_LEVEL_DESC_BY_TEMPLATE: dict[str, str] = {
    "第{zh}节": "第X节（第一节、第二节…）",
    "{zh}": "中文数字（一、二、三…）",
    "{num}": "阿拉伯数字（1、2、3…）",
    "{full}": "点分编号（1.1、1.2…）",
    "{num}）": "数字括号（1）、2）…）",
    "{alpha}": "小写字母（a、b…）",
}


def _render_heading_rules() -> str:
    """从实际导出模板表生成编号规范文本（单一事实源）。

    受控层级（L1~L4，HEADING_MANAGED_LEVELS）逐条从模板表翻译；L5+ 固定
    为「不强制编号」。模板表若换用未知占位符模板，降级为直述模板串。
    """
    from ..heading_standard import DEFAULT_NUMBERING_TEMPLATES, HEADING_MANAGED_LEVELS

    version = "V3.1"  # 与 heading_standard 模块文档声明的设计版本一致
    lines = []
    for lv in sorted(HEADING_MANAGED_LEVELS):
        tpl = DEFAULT_NUMBERING_TEMPLATES.get(lv, {}).get("numbering_template", "")
        desc = _LEVEL_DESC_BY_TEMPLATE.get(tpl, f"模板 {tpl!r}（请联系管理员确认导出侧已支持）")
        lines.append(f"- {_LEVEL_CN_NAMES.get(lv, f'L{lv}')}：{desc}")
    lines.append("- 五级及以下：不强制编号格式，系统会识别为标题但保留你的原文编号")
    return (
        f"### 标题编号规范（{version} — L1~L4 受控，L5+ 宽松）\n\n"
        f"系统在导出 DOCX 时按以下规范自动编号（你无需在 title 中包含编号）：\n"
        + "\n".join(lines)
        + "\n\n**重要**：title 字段只填纯文本标题，不要带任何编号前缀"
        "（如不要写\"第一节、XX\"或\"1.1 XX\"，只写\"XX\"）。"
    )


SHARED_HEADING_RULES = _render_heading_rules()

